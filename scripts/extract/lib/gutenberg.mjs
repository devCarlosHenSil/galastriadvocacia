/**
 * Gutenberg block content → clean HTML (SPEC-DATA §3.3).
 *
 * The inner HTML of every block is preserved; only the Gutenberg markers and
 * the WordPress generated attributes (`wp-block-*` / `has-*` classes, inline
 * styles and generated ids) are removed.
 */
import { rewriteUrls, stripSrcset } from './urls.mjs';
import { repairContent } from './repairs.mjs';
import { sanitizeHtml } from './sanitize.mjs';

/** `<p>` that only contains block comments — the malformed pattern of post 723. */
const EMPTY_WRAPPER = /<p>\s*(?:<!--[^>]*-->\s*)+<\/p>/g;

/** Any Gutenberg block comment (opening, closing or self-closing). */
const BLOCK_COMMENT = /<!--\s*\/?wp:[\s\S]*?-->/g;

/**
 * @param {string} html
 * @returns {string} the HTML with the WordPress generated classes removed
 */
function cleanAttributes(html) {
  return html.replace(/<([a-zA-Z][a-zA-Z0-9]*)((?:\s+[^<>]*?)?)\/?>/g, (match, tag, attrs) => {
    let out = attrs;

    // class="wp-block-…" / class="has-…"
    out = out.replace(/\s+class\s*=\s*"([^"]*)"/gi, (m, value) => {
      const kept = value.split(/\s+/).filter((c) => c && !c.startsWith('wp-block-') && !c.startsWith('has-'));
      return kept.length ? ` class="${kept.join(' ')}"` : '';
    });
    out = out.replace(/\s+class\s*=\s*'([^']*)'/gi, (m, value) => {
      const kept = value.split(/\s+/).filter((c) => c && !c.startsWith('wp-block-') && !c.startsWith('has-'));
      return kept.length ? ` class="${kept.join(' ')}"` : '';
    });

    // inline styles generated by the editor
    out = out.replace(/\s+style\s*=\s*"[^"]*"/gi, '');
    out = out.replace(/\s+style\s*=\s*'[^']*'/gi, '');

    // ids generated by the editor
    out = out.replace(/\s+id\s*=\s*"[^"]*"/gi, '');
    out = out.replace(/\s+id\s*=\s*'[^']*'/gi, '');

    return `<${tag}${out}>`;
  });
}

/**
 * The levels of the headings of a fragment of HTML, in the order of the
 * document (D6).
 * @param {string} html
 * @returns {number[]}
 */
export function headingLevels(html) {
  return [...String(html ?? '').matchAll(/<h([1-6])\b/gi)].map((match) => Number(match[1]));
}

/**
 * @param {string} content the raw `post_content`
 * @returns {{ html: string, removedWrappers: number, textParagraphs: number }}
 */
export function convertGutenberg(content, applied) {
  const source = content ?? '';

  // 1. the malformed `<p><!-- /wp:paragraph --><!-- wp:paragraph --></p>`
  const wrappers = source.match(EMPTY_WRAPPER) ?? [];
  let html = source.replace(EMPTY_WRAPPER, '');

  // 2. every Gutenberg block comment
  html = html.replace(BLOCK_COMMENT, '');

  // 3. attributes generated by WordPress
  html = cleanAttributes(html);

  // 4. paragraphs that carry no text (a non breaking space only, for example)
  html = html.replace(/<p(?:\s[^>]*)?>\s*<\/p>/gi, '');

  // 5. URLs and responsive image attributes
  html = repairContent(stripSrcset(rewriteUrls(html)), applied);

  // 5.1 the sanitiser (SEC-R-28): the content reaches the page through
  // `set:html` — no script, no event handler, no `javascript:` URL.
  const beforeSanitise = html;
  html = sanitizeHtml(html);

  // D6 — o sanitizador **não pode** perder os títulos: a sequência dos
  // níveis tem de ser a mesma antes e depois (a demoção `h4 → h2` das
  // políticas é feita **depois**, no overlay).
  const headingsBefore = headingLevels(beforeSanitise);
  const headingsAfter = headingLevels(html);
  if (headingsBefore.join(',') !== headingsAfter.join(',')) {
    throw new Error(
      `the sanitiser changed the outline of the document: ${headingsBefore.join(',')} -> ${headingsAfter.join(',')}`,
    );
  }

  // 6. one blank line between the blocks, no leading / trailing blank lines
  html = html
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  return {
    html,
    removedWrappers: wrappers.length,
    textParagraphs: countTextParagraphs(source),
  };
}

/**
 * Count the `<p>` elements of the original content that carry text — the
 * malformed wrappers do not count.
 * @param {string} content
 * @returns {number}
 */
export function countTextParagraphs(content) {
  const re = /<p(?:\s[^>]*)?>([\s\S]*?)<\/p>/gi;
  let count = 0;
  let m;
  while ((m = re.exec(content)) !== null) {
    const inner = m[1].replace(BLOCK_COMMENT, '').replace(/<[^>]*>/g, '').trim();
    if (inner.length > 0) count++;
  }
  return count;
}

/**
 * @param {string} html
 * @returns {string} the plain text of an HTML fragment
 */
export function htmlToText(html) {
  return html
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * @param {string} html
 * @returns {number} the number of words of the plain text
 */
export function countWords(html) {
  const text = htmlToText(html);
  if (!text) return 0;
  return text.split(/\s+/).filter(Boolean).length;
}

/**
 * The first paragraph of a body, as plain text.
 * @param {string} content the raw `post_content`
 * @returns {string}
 */
export function firstParagraphText(content) {
  const re = /<p(?:\s[^>]*)?>([\s\S]*?)<\/p>/gi;
  let m;
  while ((m = re.exec(content)) !== null) {
    const text = htmlToText(m[1]);
    if (text.length > 0) return text;
  }
  return '';
}
